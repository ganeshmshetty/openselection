import AppKit
import XCTest
@testable import OpenSelection

final class PasteboardSnapshotTests: XCTestCase {
    private static let pasteboardName = NSPasteboard.Name("com.openselection.tests.snapshot")

    @MainActor
    private func makePasteboard() -> NSPasteboard {
        let pasteboard = NSPasteboard(name: Self.pasteboardName)
        pasteboard.clearContents()
        return pasteboard
    }

    @MainActor
    func testRestoreDoesNotMarkOrdinaryContentConcealed() {
        let pasteboard = makePasteboard()
        let item = NSPasteboardItem()
        item.setString("restored text", forType: .string)
        pasteboard.writeObjects([item])

        let snapshot = PasteboardSnapshot.capture(pasteboard)
        pasteboard.clearContents()
        snapshot.restore(to: pasteboard, transientMarkers: true)

        let restored = pasteboard.pasteboardItems?.first
        XCTAssertEqual(restored?.string(forType: .string), "restored text")
        XCTAssertTrue(restored?.types.contains(PasteboardSnapshot.transientType) == true)
        XCTAssertTrue(restored?.types.contains(PasteboardSnapshot.autoGeneratedType) == true)
        XCTAssertTrue(restored?.types.contains(PasteboardSnapshot.modifiedType) == true)
        XCTAssertFalse(restored?.types.contains(PasteboardSnapshot.concealedType) == true)
    }

    @MainActor
    func testRestorePreservesOriginalConcealedMarker() {
        let pasteboard = makePasteboard()
        let item = NSPasteboardItem()
        item.setString("secret", forType: .string)
        item.setData(Data(), forType: PasteboardSnapshot.concealedType)
        pasteboard.writeObjects([item])

        let snapshot = PasteboardSnapshot.capture(pasteboard)
        pasteboard.clearContents()
        snapshot.restore(to: pasteboard, transientMarkers: true)

        let restored = pasteboard.pasteboardItems?.first
        XCTAssertTrue(restored?.types.contains(PasteboardSnapshot.concealedType) == true)
        XCTAssertEqual(restored?.string(forType: .string), "secret")
    }
}
